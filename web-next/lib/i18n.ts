export function translate(language: RiderLanguage, key: string, replacements?: Record<string, string | number>): string {
  const message = messages[key as keyof typeof messages];
  let value: string = message ? message[language === "pl" ? 0 : language === "en" ? 1 : 2] : key;
  for (const [name, replacement] of Object.entries(replacements ?? {})) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}