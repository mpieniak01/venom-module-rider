async page => {
  const check=(value,message)=>{if(!value)throw new Error(message)};
  const origin=new URL(page.url());
  check(["localhost","127.0.0.1"].includes(origin.hostname),"loopback required");
  const base=origin.origin+"/api/v1/rider";
  const config=await(await page.request.get(base+"/config")).json();
  check(config.devices.every(item=>item.mode==="demo"),"fixture-only required");
  const mutations=[];
  page.on("request",request=>{if(request.method()==="POST"&&/\/rider\/(control|goal|resource)/.test(request.url()))mutations.push(request.url())});
  const sessions=await(await page.request.get(base+"/samples/sessions")).json();
  const session=sessions.sessions.find(item=>item.policy?.scene_group==="inputs-floor");
  check(session,"historical dataset required");
  await page.reload();
  await page.getByTestId("samples-browser").locator("summary").first().click();
  await page.getByTestId("samples-session").selectOption(session.session_id);
  const panel=page.getByTestId("analysis-panel");
  await panel.locator("summary").filter({hasText:"Parametry analizy"}).click();
  await panel.getByLabel("Maksymalna liczba klatek",{exact:true}).fill("2");
  await page.getByTestId("analysis-start").click();
  await page.waitForFunction(()=>document.querySelector('[data-testid="analysis-status"]')?.textContent?.includes("Ukończono"),{timeout:60000});
  const first=await page.getByTestId("analysis-run").inputValue();
  await page.getByTestId("analysis-frame").selectOption("1");
  await panel.locator('img').first().waitFor();
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('[data-testid="analysis-panel"] img')).every(image=>image.complete&&image.naturalWidth>0));
  const firstReport=await(await page.request.get(base+"/analysis/runs/"+first+"/artifacts/report.json")).json();
  check(firstReport.rows.length===2&&firstReport.summary.false_go===null,"report/GT contract");
  check(firstReport.context.spec.geometry.mode==="image","geometry not frozen");
  await page.getByTestId("analysis-profile").selectOption("da3-small-280");
  await page.getByTestId("analysis-start").click();
  await page.waitForFunction(previous=>document.querySelector('[data-testid="analysis-run"]')?.value!==previous,first);
  await page.waitForFunction(()=>document.querySelector('[data-testid="analysis-status"]')?.textContent?.includes("Ukończono"),{timeout:60000});
  const second=await page.getByTestId("analysis-run").inputValue();
  await panel.getByLabel("Porównaj z przebiegiem",{exact:true}).selectOption(first);
  await page.getByTestId("analysis-compare").click();
  await panel.getByText("Te same wejścia i rewizje etykiet.",{exact:true}).waitFor();
  const comparison=await(await page.request.get(base+"/analysis/compare?first="+first+"&second="+second)).json();
  check(comparison.aligned_inputs_and_labels,"mismatched model inputs");
  const downloadPromise=page.waitForEvent("download");
  await page.getByTestId("analysis-report").click();
  const download=await downloadPromise;
  check(!await download.failure(),"report download failed");
  await page.setViewportSize({width:1440,height:1000});
  await panel.scrollIntoViewIfNeeded();
  await page.screenshot({path:"output/playwright/259c-analysis-desktop.png"});
  await page.setViewportSize({width:390,height:844});
  await panel.scrollIntoViewIfNeeded();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"mobile horizontal overflow");
  await page.screenshot({path:"output/playwright/259c-analysis-mobile.png"});
  await page.setViewportSize({width:1440,height:1000});
  check(mutations.length===0,"offline analysis mutated physical domain");
  return {flow:"PASS",session:session.session_id,first,second,realModels:true,matchingSources:true,unreviewedQualityNA:true,offlineMutations:mutations.length,reportDownload:true,mobile:true};
}
